    static var all: [Exercise] { training + mobility }

    static func exercise(named name: String) -> Exercise? {
        all.first { $0.name == name }
    }

    static func mobility(in region: MobilityRegion) -> [Exercise] {
        mobility.filter { $0.region == region }
    }
